#!/usr/bin/env bash
set -euo pipefail

# DRAKVUF Sandbox Environment Repair & Boot Recovery Utility
# Author: Nitiraj V. Kulkarni (https://nitirajkulkarni.in)

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "${SCRIPT_DIR}"

if [[ $EUID -ne 0 ]]; then
    echo "[-] Error: Run repair as root (sudo ./repair.sh)" >&2
    exit 1
fi

MODE="${1:-all}"

if [[ "${MODE}" == "--restore-ubuntu-boot" || "${MODE}" == "--restore-ubuntu" ]]; then
    echo "[!] Restoring default GRUB boot to standard Ubuntu Linux kernel..."
    if [[ -f /etc/default/grub.d/xen.cfg ]]; then
        mv /etc/default/grub.d/xen.cfg /etc/default/grub.d/xen.cfg.disabled
        echo "[+] Moved /etc/default/grub.d/xen.cfg to .disabled"
    fi
    sed -i -E 's/^GRUB_DEFAULT=.*/GRUB_DEFAULT=0/' /etc/default/grub 2>/dev/null || true
    update-grub
    echo "[✓] Bootloader restored. Host will now boot standard Ubuntu Linux by default."
    exit 0
fi

if [[ "${MODE}" == "--enable-xen-boot" ]]; then
    echo "[!] Re-enabling Xen Hypervisor as default boot entry..."
    if [[ -f /etc/default/grub.d/xen.cfg.disabled ]]; then
        mv /etc/default/grub.d/xen.cfg.disabled /etc/default/grub.d/xen.cfg
        echo "[+] Restored /etc/default/grub.d/xen.cfg"
    fi
    update-grub
    echo "[✓] Xen boot entry restored. Host will boot into Xen Hypervisor upon reboot."
    exit 0
fi

echo "================================================================="
echo "  DRAKVUF Sandbox Automated Repair & System Qualification Suite  "
echo "================================================================="

# 1. Ensure Xen & Storage Modules are configured for early boot
CURR_KERNEL="$(uname -r)"
echo "[*] Step 1: Checking kernel storage & Xen hypervisor drivers for ${CURR_KERNEL}..."
apt-get install -y "linux-modules-extra-${CURR_KERNEL}" 2>/dev/null || true
for mod in xen-evtchn xen-privcmd xen-gntdev xen-blkfront xen-netfront ahci nvme vmw_pvscsi mptspi mptsas ata_piix sd_mod scsi_mod; do
    modprobe "${mod}" 2>/dev/null || true
done

# 2. Configure Dracut and initramfs drivers
echo "[*] Step 2: Ensuring early-boot ramdisk includes Xen & disk controllers..."
if command -v dracut >/dev/null 2>&1 || [[ -d /etc/dracut.conf.d ]]; then
    mkdir -p /etc/dracut.conf.d
    cat > /etc/dracut.conf.d/xen.conf << 'EOF'
# Generated by drakvuf-auto-installer repair utility
add_drivers+=" xen-blkfront xen-netfront xen-privcmd xen-evtchn xen-gntdev ahci nvme vmw_pvscsi mptspi mptsas ata_piix sd_mod scsi_mod virtio_blk virtio_pci virtio_scsi "
EOF
    echo "[+] Updated /etc/dracut.conf.d/xen.conf (with VMware/Xen/NVMe/SATA add_drivers)"
    if command -v dracut >/dev/null 2>&1; then
        echo "[*] Regenerating Dracut image for active kernel ${CURR_KERNEL}..."
        dracut --force --add-drivers "xen-blkfront xen-netfront xen-privcmd xen-evtchn xen-gntdev ahci nvme vmw_pvscsi mptspi mptsas ata_piix sd_mod scsi_mod" "/boot/initrd.img-${CURR_KERNEL}" "${CURR_KERNEL}" || dracut --force || true
    fi
fi

if [[ -d /etc/initramfs-tools ]]; then
    mkdir -p /etc/initramfs-tools
    for mod in xen-blkfront xen-netfront xen-privcmd xen-evtchn xen-gntdev ahci nvme vmw_pvscsi mptspi mptsas ata_piix sd_mod scsi_mod; do
        if ! grep -q "^${mod}" /etc/initramfs-tools/modules 2>/dev/null; then
            echo "${mod}" >> /etc/initramfs-tools/modules
        fi
    done
    if command -v update-initramfs >/dev/null 2>&1; then
        echo "[*] Regenerating initramfs image for active kernel ${CURR_KERNEL}..."
        update-initramfs -u -k "${CURR_KERNEL}" 2>/dev/null || update-initramfs -u 2>/dev/null || true
    fi
fi

# 3. Clean and sanitize GRUB commandline parameters for Xen Dom0
echo "[*] Step 3: Sanitizing GRUB Xen parameters (removing interrupt-breaking flags)..."
CLEAN_XEN_CMDLINE='GRUB_CMDLINE_XEN_DEFAULT="dom0_mem=4096M,max:4096M dom0_max_vcpus=2 altp2m=1"'

if [[ -f /etc/default/grub ]]; then
    if grep -q "GRUB_CMDLINE_XEN_DEFAULT=" /etc/default/grub; then
        sed -i -E "s|^GRUB_CMDLINE_XEN_DEFAULT=.*|${CLEAN_XEN_CMDLINE}|" /etc/default/grub
    else
        echo "${CLEAN_XEN_CMDLINE}" >> /etc/default/grub
    fi
    # Ensure safe timeout and menu visibility
    sed -i -E 's/^GRUB_TIMEOUT=.*/GRUB_TIMEOUT=10/' /etc/default/grub || true
    sed -i -E 's/^GRUB_TIMEOUT_STYLE=.*/GRUB_TIMEOUT_STYLE=menu/' /etc/default/grub || true
fi

if [[ -f /etc/default/grub.d/xen.cfg ]]; then
    # Keep xen.cfg aligned with clean cmdline
    sed -i -E "s|^GRUB_CMDLINE_XEN_DEFAULT=.*|${CLEAN_XEN_CMDLINE}|" /etc/default/grub.d/xen.cfg 2>/dev/null || true
fi

echo "[*] Step 4: Updating GRUB bootloader..."
update-grub

# 5. Restart Xen & supporting daemons
echo "[*] Step 5: Restarting hypervisor and telemetry daemons..."
systemctl restart xencommons 2>/dev/null || true
systemctl restart redis-server 2>/dev/null || true
systemctl restart drakweb 2>/dev/null || true

# 6. Reload dynamic linker cache
echo "[*] Step 6: Updating shared library cache (LibVMI / LibDRAKVUF)..."
ldconfig

echo "================================================================="
echo "[✓] Automated repair completed successfully."
echo "    - To verify system status: sudo ./diagnose.sh"
echo "    - If you need to reboot into normal Ubuntu: sudo ./repair.sh --restore-ubuntu-boot"
echo "================================================================="

if [[ "${MODE}" == "--reboot" ]]; then
    echo "[*] Initiating automatic system reboot in 3 seconds..."
    sleep 3
    systemctl reboot
fi
